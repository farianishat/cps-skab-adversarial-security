"""## Section 4: Baseline Detector Training & Threshold Calibration
We train two complementary anomaly detectors on normal windows (`X_train`):
1. **Isolation Forest**: Trained on window summary statistics (mean, standard deviation, and final reading per channel).
2. **PyTorch LSTM Autoencoder**: Sequence-to-sequence recurrent autoencoder trained to reconstruct normal 60-second windows across all 8 sensors.

Both alarm thresholds are calibrated at the **99th percentile** of anomaly-free validation scores (`X_val`).
"""

class LSTMAutoencoder(nn.Module):
    def __init__(self, n_features: int, hidden_dim: int, latent_dim: int):
        super().__init__()
        self.encoder = nn.LSTM(n_features, hidden_dim, batch_first=True)
        self.to_latent = nn.Linear(hidden_dim, latent_dim)
        self.from_latent = nn.Linear(latent_dim, hidden_dim)
        self.decoder = nn.LSTM(hidden_dim, hidden_dim, batch_first=True)
        self.out_proj = nn.Linear(hidden_dim, n_features)

    def forward(self, x):
        _, (h_n, _) = self.encoder(x)
        z = torch.relu(self.to_latent(h_n[-1]))
        h_dec = torch.relu(self.from_latent(z)).unsqueeze(1).repeat(1, x.size(1), 1)
        dec_out, _ = self.decoder(h_dec)
        return self.out_proj(dec_out)

def extract_if_features(X_win: np.ndarray) -> np.ndarray:
    mean_f = X_win.mean(axis=1)
    std_f = X_win.std(axis=1)
    last_f = X_win[:, -1, :]
    return np.hstack([mean_f, std_f, last_f])

