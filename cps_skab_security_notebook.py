"""## Section 6: Gradient-Based White-Box Evasion Attack
We implement Projected Gradient Descent (PGD) to spoof anomalous telemetry windows (`X_test_anom`) so that the LSTM Autoencoder's reconstruction error falls below `ae_thresh`.
* Because `X_test` is standardized by the anomaly-free `StandardScaler`, an $L_\infty$ perturbation bound of `eps_std` in standardized space corresponds **exactly** to $\epsilon \times \sigma_i$ in physical units for each sensor $i$.
* We then invert the scaling to plot the physical sensor waveforms before and after spoofing (`05_clean_vs_perturbed_overlay.png`).
"""

def evasion_attack_pgd(model: nn.Module, X_anom: np.ndarray, eps_std: float, steps: int, alpha_ratio: float) -> np.ndarray:
    if eps_std <= 0.0:
        return X_anom.copy()
    model.eval()
    x_orig = torch.tensor(X_anom, dtype=torch.float32)
    x_adv = x_orig.clone().detach()
    alpha = max(eps_std * alpha_ratio, eps_std / 6.0)

    with torch.no_grad():
        # Normal manifold target reconstruction anchored from the clean pass
        target_recon = model(x_orig).detach() * 0.35

    for _ in range(steps):
        x_adv.requires_grad_(True)
        recon = model(x_adv)
        # Minimize actual detector MSE + pull toward normal manifold
        loss = torch.sum(torch.mean((recon - x_adv) ** 2, dim=(1, 2)) + 0.5 * torch.mean((x_adv - target_recon) ** 2, dim=(1, 2)))
        model.zero_grad()
        loss.backward()
        with torch.no_grad():
            x_adv = x_adv - alpha * x_adv.grad.sign()
            eta = torch.clamp(x_adv - x_orig, min=-eps_std, max=eps_std)
            x_adv = (x_orig + eta).detach()
    return x_adv.numpy()

