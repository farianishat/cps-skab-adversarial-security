def compute_detection_delay(y_true: np.ndarray, y_pred: np.ndarray, file_ids: np.ndarray) -> float:
    delays = []
    for fid in np.unique(file_ids):
        mask = (file_ids == fid)
        yt, yp = y_true[mask], y_pred[mask]
        starts = np.where((yt == 1) & (np.concatenate(([0], yt[:-1])) == 0))[0]
        for s in starts:
            end = s
            while end < len(yt) and yt[end] == 1:
                end += 1
            detected_indices = np.where(yp[s:end] == 1)[0]
            if len(detected_indices) > 0:
                delays.append(int(detected_indices[0]))
    return float(np.mean(delays)) if delays else float("nan")

def evaluate_detector(name: str, scores: np.ndarray, thresh: float, y_true: np.ndarray, file_ids: np.ndarray):
    preds = (scores >= thresh).astype(int)
    metrics = {
        "Detector": name,
        "F1": round(f1_score(y_true, preds, zero_division=0), 4),
        "Precision": round(precision_score(y_true, preds, zero_division=0), 4),
        "Recall": round(recall_score(y_true, preds, zero_division=0), 4),
        "ROC-AUC": round(roc_auc_score(y_true, scores), 4),
        "Mean Delay (s)": round(compute_detection_delay(y_true, preds, file_ids), 2)
    }
    return metrics, preds

