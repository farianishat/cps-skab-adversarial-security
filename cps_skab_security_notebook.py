"""## Section 7: Perturbation Budget Sweep & Ensemble Defense Evaluation
We now sweep the $L_\infty$ attack budget across `[0.0, 0.05, 0.10, 0.15, 0.20, 0.30, 0.40, 0.50]` (as a fraction of each sensor's normal standard deviation) and compare four detection configurations:
1. **Undefended LSTM-AE**: Standalone neural reconstruction detector.
2. **Isolation Forest (Zero-Order)**: Gradient-free tree detector operating on summary statistics.
3. **Defense 1 (AE + IF Hybrid Ensemble)**: Logical OR combiner of the LSTM Autoencoder and Isolation Forest.
4. **Defense 2 (Temporal Residual Smoothing + Ensemble)**: Convolving sequential autoencoder errors with a moving-average filter before combining with the Isolation Forest.
"""

budgets = CFG["attack"]["budgets_std_fraction"]
steps = CFG["attack"]["steps"]
alpha_ratio = CFG["attack"]["alpha_ratio"]
kernel = CFG["attack"]["smoothing_kernel"]

# Evaluate across all anomalous windows detected by the baseline LSTM-AE at eps = 0
base_detected_mask = (clean_err_demo >= ae_thresh)
eval_mask = base_detected_mask if np.sum(base_detected_mask) > 0 else np.ones(len(X_test_anom), dtype=bool)

sweep_rows = []
adv_examples_cache = {}

for eps in budgets:
    X_adv = evasion_attack_pgd(model, X_test_anom, eps, steps, alpha_ratio)
    adv_examples_cache[eps] = X_adv

    err_ae = get_ae_errors(X_adv)
    err_if = get_if_scores(X_adv)

    det_ae = (err_ae >= ae_thresh)
    # Zero-order Isolation Forest evaluated on windows originally detected by the AE
    det_if = (err_if >= if_thresh) & base_detected_mask
    det_ens = det_ae | det_if

    err_ae_smooth = np.convolve(err_ae, np.ones(kernel) / kernel, mode="same")
    det_smooth = (err_ae_smooth >= ae_thresh * 0.85) | det_if

    sweep_rows.append({
        "Budget (Std Fraction)": eps,
        "Undefended LSTM-AE (%)": round(np.mean(det_ae[eval_mask]) * 100.0, 2),
        "Isolation Forest (%)": round(np.mean(det_if[eval_mask]) * 100.0, 2),
        "Defense 1: AE+IF Ensemble (%)": round(np.mean(det_ens[eval_mask]) * 100.0, 2),
        "Defense 2: Smoothed AE+IF (%)": round(np.mean(det_smooth[eval_mask]) * 100.0, 2)
    })

df_sweep = pd.DataFrame(sweep_rows)
display(df_sweep)

# Figure 6: Detection Rate vs Attack Budget Curve
fig, ax = plt.subplots(figsize=(8.5, 5))
