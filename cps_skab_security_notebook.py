ax.plot(df_sweep["Budget (Std Fraction)"], df_sweep["Isolation Forest (%)"], "s--", color="#ff7f0e", lw=2, label="Isolation Forest (Zero-Order)")
ax.plot(df_sweep["Budget (Std Fraction)"], df_sweep["Defense 1: AE+IF Ensemble (%)"], "^-", color="#1f77b4", lw=2.2, label="Defense 1: AE + IF Ensemble")
ax.plot(df_sweep["Budget (Std Fraction)"], df_sweep["Defense 2: Smoothed AE+IF (%)"], "d-", color="#2ca02c", lw=2.2, label="Defense 2: Smoothed AE + IF Ensemble")

ax.set_title("Adversarial Robustness: Anomaly Detection Rate vs. Perturbation Budget")
